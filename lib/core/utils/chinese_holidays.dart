/// 中国节假日工具类
///
/// 提供中国传统节日和法定假日的日期查询功能
/// 包含农历节日（春节、端午、中秋等）和公历节日（元旦、国庆等）
class ChineseHolidays {
  /// 私有构造函数，防止实例化
  ChineseHolidays._();

  /// 获取指定日期的节假日名称
  ///
  /// [date] 要查询的日期
  /// 返回节假日名称，如果不是节假日则返回 null
  static String? getHoliday(DateTime date) {
    // 先检查公历节日
    final solarHoliday = _getSolarHoliday(date);
    if (solarHoliday != null) return solarHoliday;

    // 再检查农历节日
    final lunarHoliday = _getLunarHoliday(date);
    if (lunarHoliday != null) return lunarHoliday;

    return null;
  }

  /// 获取公历节日
  static String? _getSolarHoliday(DateTime date) {
    final key = '${date.month}-${date.day}';
    return _solarHolidays[key];
  }

  /// 获取农历节日
  ///
  /// 由于农历计算复杂，这里预先计算好 2024-2030 年的主要农历节日日期
  static String? _getLunarHoliday(DateTime date) {
    final key = '${date.year}-${date.month}-${date.day}';
    return _lunarHolidaysCache[key];
  }

  /// 判断是否为节假日
  static bool isHoliday(DateTime date) {
    return getHoliday(date) != null;
  }

  /// 判断是否为调休工作日
  ///
  /// [date] 要查询的日期
  /// 返回 true 表示是调休工作日（周末需要上班）
  static bool isWorkday(DateTime date) {
    final key = '${date.year}-${date.month}-${date.day}';
    return _workdaysCache.contains(key);
  }

